function interpolate(text, vars) {
  if (!text) return text;
  return text.replace(/\{(\w+)\}/g, (m, k) => (vars && vars[k] != null ? vars[k] : m));
}

function resolvePath(dict, key) {
  const parts = key.split('.');
  let cur = dict;
  for (const p of parts) {
    if (cur == null) return undefined;
    cur = cur[p];
  }
  return typeof cur === 'string' ? cur : undefined;
}

const LanguageContext = createContext({ lang: 'en', t: (k, vars) => k, setLang: () => {} });

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState('en');
  const dict = translations[lang] || translations.en;

  const t = (key, vars) => {
    const direct = dict[key] ?? translations.en[key];
    const str = typeof direct === 'string'
      ? direct
      : (resolvePath(dict, key) ?? resolvePath(translations.en, key) ?? key);
    return interpolate(str, vars);
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}

